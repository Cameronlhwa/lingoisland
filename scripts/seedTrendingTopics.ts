async function seed() {
  try {
    console.log("Starting trending_topics seed...");

    // Get current Monday
    const weekOf = getCurrentMonday();
    const weekOfStr = weekOf.toISOString().split("T")[0];

    console.log(`Seeding topics for week of: ${weekOfStr}`);

    // Check if this week already has topics
    const { data: existing, error: checkError } = await supabase
      .from("trending_topics")
      .select("id")
      .eq("week_of", weekOfStr)
      .limit(1);

    if (checkError) {
      console.error("Error checking existing topics:", checkError);
      process.exit(1);
    }

    if (existing && existing.length > 0) {
      console.log("Topics already exist for this week. Skipping seed.");
      process.exit(0);
    }

    // Shuffle topics and select 12 featured with quotas
    // First, always include these 6 specific topics
    const requiredSlugs = ["relationships", "restaurants", "complaining", "politics", "government", "church"];
    const requiredTopics = topicsPool.filter(t => requiredSlugs.includes(t.slug));
    
    // Remaining topics to choose from (excluding required ones)
    const remainingTopics = topicsPool.filter(t => !requiredSlugs.includes(t.slug));
    const shuffled = [...remainingTopics].sort(() => Math.random() - 0.5);
    
    // Category quotas for the remaining 6 featured topics
    const categoryQuotas: Record<string, number> = {
      "Everyday errands": 1,
      "Travel": 1,
      "Health": 1,
      "Entertainment & hobbies": 1,
      "Work/School": 1,
      "Unexpected problems": 1,
    };

    const featuredTopics: Topic[] = [...requiredTopics]; // Start with required 6
    const categoryCount: Record<string, number> = {};
    
    // Count categories already used by required topics
    for (const topic of requiredTopics) {
      categoryCount[topic.category] = (categoryCount[topic.category] || 0) + 1;
    }

    // Select remaining 6 featured topics with category diversity
    for (const topic of shuffled) {
      const count = categoryCount[topic.category] || 0;
      const quota = categoryQuotas[topic.category] || 0;
      
      if (count < quota) {
        featuredTopics.push(topic);
        categoryCount[topic.category] = count + 1;
      }

      if (featuredTopics.length >= 12) break;
    }

    // Prepare insert data
    const insertData = topicsPool.map((topic, index) => {
      const isFeatured = featuredTopics.some(ft => ft.slug === topic.slug);
      const rank = isFeatured 
        ? featuredTopics.findIndex(ft => ft.slug === topic.slug) + 1
        : 13 + index;

      return {
        slug: topic.slug,
        title_en: topic.title_en,
        title_zh: topic.title_zh,
        category: topic.category,
        tags: topic.tags,
        level: topic.level,
        starter_prompts: topic.starter_prompts,
        week_of: weekOfStr,
        rank,
        is_featured: isFeatured,
      };
    });

    // Insert in batches of 100
    const batchSize = 100;
    for (let i = 0; i < insertData.length; i += batchSize) {
      const batch = insertData.slice(i, i + batchSize);
      const { error: insertError } = await supabase
        .from("trending_topics")
        .insert(batch);

      if (insertError) {
        console.error(`Error inserting batch ${i / batchSize + 1}:`, insertError);
        process.exit(1);
      }

      console.log(`Inserted batch ${i / batchSize + 1} (${batch.length} topics)`);
    }

    console.log(`✅ Successfully seeded ${insertData.length} topics`);
    console.log(`   - ${featuredTopics.length} featured topics`);
    console.log(`   - ${insertData.length - featuredTopics.length} regular topics`);
    console.log("\nFeatured topics by category:");
    Object.entries(categoryCount).forEach(([cat, count]) => {
      console.log(`   - ${cat}: ${count}`);
    });

  } catch (error) {
    console.error("Unexpected error during seed:", error);
    process.exit(1);
  }
}

seed();
